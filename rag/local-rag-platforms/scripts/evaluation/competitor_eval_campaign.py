@dataclass(frozen=True)
class CampaignConfig:
    repo_root: Path = ROOT
    package_root: Path | None = None
    output_root: Path | None = None
    checkpoint: Path | None = None
    progress_log: Path | None = None
    campaign_id: str = DEFAULT_CAMPAIGN_ID
    execute: bool = False
    runner_path: Path | None = None
    repeats: int = DEFAULT_REPEATS
    top_k: int = DEFAULT_TOP_K
    poll_seconds: float = DEFAULT_POLL_SECONDS
    service_timeout: float = DEFAULT_SERVICE_TIMEOUT
    provider_timeout: float = DEFAULT_PROVIDER_TIMEOUT
    upload_timeout: float = DEFAULT_UPLOAD_TIMEOUT
    index_timeout: float = DEFAULT_INDEX_TIMEOUT
    query_timeout: float = DEFAULT_QUERY_TIMEOUT
    qa_timeout: float = DEFAULT_QA_TIMEOUT
    provider: str = DEFAULT_PROVIDER
    evaluation_stage: str = "all"
    download: bool = False

    def __post_init__(self) -> None:
        repo = Path(self.repo_root).expanduser().resolve()
        object.__setattr__(self, "repo_root", repo)
        object.__setattr__(self, "package_root", _resolve(repo, self.package_root or Path(".local-services/competitor-eval-ready/v1")))
        object.__setattr__(self, "output_root", _resolve(repo, self.output_root or Path("runs/competitor-eval-campaign")))
        object.__setattr__(self, "checkpoint", _resolve(repo, self.checkpoint or Path(".local-services/competitor-eval-campaign/campaign.json")))
        progress = self.progress_log or (Path(self.checkpoint).parent / "progress.jsonl")
        object.__setattr__(self, "progress_log", _resolve(repo, progress))
        object.__setattr__(self, "runner_path", _resolve(repo, self.runner_path or Path("local-rag-platforms/scripts/evaluation/competitor_eval_runner.py")))
        if self.repeats < 1 or self.top_k < 1:
            raise CampaignError("REPEATS_AND_TOP_K_MUST_BE_POSITIVE")
        if self.download:
            raise CampaignError("DOWNLOAD_REFUSED: campaign consumes only already materialized local packages")
        if self.evaluation_stage not in {"all", "qa"}:
            raise CampaignError("EVALUATION_STAGE_MUST_BE_ALL_OR_QA")
        _reject_taas(self.provider, field="provider")


