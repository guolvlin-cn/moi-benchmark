def _parse_env_file(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.is_file():
        return values
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[7:].lstrip()
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key):
            continue
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
            value = value[1:-1]
        values[key] = value
    return values


def _set_aliases(env: dict[str, str], names: Iterable[str]) -> None:
    value = next((env.get(name, "").strip() for name in names if env.get(name, "").strip()), "")
    if value:
        for name in names:
            env[name] = value


def load_campaign_env(repo_root: Path | str, platform: str, *, base_env: Mapping[str, str] | None = None) -> dict[str, str]:
    """Load ignored local credentials while keeping values out of artifacts.

    The returned mapping is for a child process only.  It is never serialized
    into the checkpoint or progress log.  TaaS-named variables are excluded;
    the runner receives Qianfan and MaaS provider values instead.
    """

    repo = Path(repo_root).expanduser().resolve()
    platform = _normal_platform(platform)
    # All API keys, provider credentials, app IDs and chat IDs are resolved
    # from the repository-root .env.  Runtime files remain for non-secret
    # deployment details and are intentionally not part of this child env.
    paths = [repo / ".env"]

    merged: dict[str, str] = {}
    for path in paths:
        for key, value in _parse_env_file(path).items():
            if key.startswith("TAAS_"):
                continue
            merged[key] = value

    explicit = dict(base_env) if base_env is not None else dict(os.environ)
    for key, value in explicit.items():
        if key.startswith("TAAS_"):
            continue
        merged[key] = value

    _set_aliases(merged, ("QIANFAN_API_KEY", "QIANFAN_APIKEY"))
    _set_aliases(merged, ("MAAS_API_KEY", "MAAS_APIKEY"))
    _set_aliases(merged, ("DIFY_LOCAL_API_KEY", "DIFY_API_KEY"))
    _set_aliases(merged, ("DIFY_LOCAL_APP_ID", "DIFY_APP_ID"))
    _set_aliases(merged, ("DIFY_LOCAL_DATASET_API_KEY", "DIFY_DATASET_API_KEY"))
    _set_aliases(merged, ("DIFY_LOCAL_DATASET_ID", "DIFY_DATASET_ID"))
    _set_aliases(merged, ("DIFY_LOCAL_BASE_URL", "DIFY_API_BASE_URL"))
    _set_aliases(merged, ("FASTGPT_LOCAL_API_KEY", "FASTGPT_API_KEY"))
    _set_aliases(merged, ("FASTGPT_LOCAL_APP_ID", "FASTGPT_APP_ID"))
    _set_aliases(merged, ("FASTGPT_LOCAL_BASE_URL", "FASTGPT_BASE_URL"))
    _set_aliases(merged, ("MAXKB_ADMIN_TOKEN", "MAXKB_TOKEN", "MAXKB_ADMIN_API_KEY"))
    _set_aliases(merged, ("MAXKB_APP_KEY", "MAXKB_APPLICATION_KEY", "MAXKB_API_KEY"))
    _set_aliases(merged, ("MAXKB_APPLICATION_ID", "MAXKB_APP_ID"))

    if platform == "maxkb_local":
        token_path = Path(
            merged.get("MAXKB_ADMIN_TOKEN_FILE", "")
            or repo / ".local-services/maxkb_local/secrets/admin.token"
        ).expanduser()
        if not token_path.is_absolute():
            token_path = repo / token_path
        merged["MAXKB_ADMIN_TOKEN_FILE"] = str(token_path.resolve())
        if not merged.get("MAXKB_ADMIN_TOKEN", "").strip() and token_path.is_file():
            merged["MAXKB_ADMIN_TOKEN"] = token_path.read_text(encoding="utf-8", errors="replace").strip()
        merged.setdefault("MAXKB_ADMIN_BASE_URL", "http://127.0.0.1:8090/admin/api")
        merged.setdefault("MAXKB_OPENAI_BASE_URL", "http://127.0.0.1:8090/chat/api")

    # The runner itself rejects these active provider fields.  Check them at
    # the campaign boundary so no child process is launched after a refusal.
    allow_dify_generic = merged.get("DIFY_ALLOW_GENERIC_COMPAT_ADAPTER", "").strip() == "1"
    for key in (
        "QIANFAN_BASE_URL",
        "QIANFAN_LLM_MODEL",
        "QIANFAN_IMAGE_LLM_MODEL",
        "QIANFAN_VISION_MODEL",
        "MAAS_BASE_URL",
        "MAAS_EMBEDDING_MODEL",
        "DIFY_EMBEDDING_PROVIDER",
        "DIFY_MAAS_EMBEDDING_PROVIDER",
        "DIFY_QIANFAN_LLM_PROVIDER",
        "MAXKB_ADMIN_BASE_URL",
        "MAXKB_OPENAI_BASE_URL",
    ):
        if merged.get(key):
            if (
                allow_dify_generic
                and key in {"DIFY_EMBEDDING_PROVIDER", "DIFY_MAAS_EMBEDDING_PROVIDER", "DIFY_QIANFAN_LLM_PROVIDER"}
                and merged[key] == DIFY_GENERIC_OAI_ADAPTER
            ):
                continue
            _reject_taas(merged[key], field=key)

    # Some local FastGPT env files retain a stale TaaS selector even though
    # the campaign uses the runner's Qianfan/MaaS path.  Do not pass that
    # selector to a child process; a TaaS provider must never be activated by
    # this orchestrator.
    for key in ("FASTGPT_MODEL_PROVIDER", "FASTGPT_PROVIDER", "MODEL_PROVIDER"):
        if any(marker in merged.get(key, "").casefold() for marker in SECRET_MARKERS):
            merged.pop(key, None)
    return merged


def _normal_platform(value: str) -> str:
    normalized = str(value).strip().casefold().replace("-", "_")
    aliases = {
        "dify": "dify_local",
        "fastgpt": "fastgpt_local",
        "maxkb": "maxkb_local",
    }
    normalized = aliases.get(normalized, normalized)
    if normalized not in PLATFORM_ORDER:
        raise CampaignError(f"PLATFORM_UNSUPPORTED:{value}")
    return normalized


def _load_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return None
    except json.JSONDecodeError as exc:
        raise CampaignError(f"JSON_INVALID:{path}") from exc


_MISSING = object()


def _command_option(command: Any, option: str) -> Any:
    if not isinstance(command, (list, tuple)):
        return _MISSING
    for index, value in enumerate(command[:-1]):
        if value == option:
            return command[index + 1]
    return _MISSING


def _legacy_checkpoint_config(payload: Mapping[str, Any]) -> dict[str, Any]:
    """Recover config from checkpoints written before the config block existed.

    Early checkpoints already recorded the effective runner command for every
    unit.  Reading the first such command keeps an interrupted campaign
    resumable even when it was planned by an older version of this module.
    """

    stored: dict[str, Any] = {}
    config = payload.get("config")
    if isinstance(config, Mapping):
        stored.update({key: config[key] for key in CHECKPOINT_CONFIG_FIELDS if key in config})
    experiment_config = payload.get("experiment_config")
    if isinstance(experiment_config, Mapping):
        for key in CHECKPOINT_CONFIG_FIELDS:
            if key not in stored and key in experiment_config:
                stored[key] = experiment_config[key]

    top_level_fields = {
        "repo_root",
        "package_root",
        "output_root",
        "campaign_id",
    }
    for key in top_level_fields:
        if key not in stored and payload.get(key) not in (None, ""):
            stored[key] = payload[key]

    policy = payload.get("policy")
    if "provider" not in stored and isinstance(policy, Mapping) and policy.get("provider") not in (None, ""):
        stored["provider"] = policy["provider"]

    command: Any = None
    units = payload.get("units")
    if isinstance(units, Mapping):
        units = list(units.values())
    if isinstance(units, list):
        for unit in units:
            if not isinstance(unit, Mapping):
                continue
            candidate = unit.get("runner_command")
            if isinstance(candidate, (list, tuple)):
                command = candidate
                break

    if command is not None:
        if "runner_path" not in stored and len(command) > 1:
            stored["runner_path"] = command[1]
        option_types: dict[str, type] = {
            "repeats": int,
            "top_k": int,
            "poll_seconds": float,
            "service_timeout": float,
            "provider_timeout": float,
            "upload_timeout": float,
            "index_timeout": float,
            "query_timeout": float,
            "qa_timeout": float,
        }
        for key, converter in option_types.items():
            if key in stored:
                continue
            value = _command_option(command, f"--{key.replace('_', '-')}")
            if value is not _MISSING:
                try:
                    stored[key] = converter(value)
                except (TypeError, ValueError) as exc:
                    raise CampaignError(f"CHECKPOINT_CONFIG_INVALID:{key}") from exc

    return stored


def _checkpoint_restore_values(path: Path) -> dict[str, Any]:
    payload = _load_json(path)
    if payload is None:
        return {}
    if not isinstance(payload, Mapping) or payload.get("schema") != CHECKPOINT_SCHEMA:
        # CampaignStore will emit the canonical checkpoint error below.  Do
        # not treat a malformed checkpoint as permission to use CLI defaults.
        return {}
    return _legacy_checkpoint_config(payload)


def _manifest_dataset(manifest: Mapping[str, Any]) -> str:
    value = manifest.get("dataset", manifest.get("dataset_id", ""))
    if isinstance(value, Mapping):
        value = value.get("id", value.get("name", ""))
    return _canonical_dataset(value)


def _manifest_condition(manifest: Mapping[str, Any], manifest_path: Path, package_root: Path, dataset: str) -> str:
    value = manifest.get("condition")
    if not value and isinstance(manifest.get("evaluation"), Mapping):
        value = manifest["evaluation"].get("condition")
    if value:
        return _safe_slug(value, 64)
    parent_name = manifest_path.parent.name
    if manifest_path.parent != package_root and _canonical_dataset(parent_name) != dataset:
        return _safe_slug(parent_name, 64)
    return "native"


def _manifest_has_taas_provider(manifest: Mapping[str, Any]) -> bool:
    values: list[Any] = []
    for key in ("provider", "model_egress"):
        values.append(manifest.get(key))
    for key in ("provider_selection", "providers"):
        value = manifest.get(key)
        if isinstance(value, Mapping):
            values.extend(value.values())
    return any(any(marker in str(item).casefold() for marker in SECRET_MARKERS) for item in values)


def _manifest_artifact_value(manifest: Mapping[str, Any], names: Iterable[str]) -> Any:
    wanted = tuple(names)
    for key in wanted:
        value = manifest.get(key)
        if value not in (None, ""):
            return value
    artifacts = manifest.get("artifacts")
    if isinstance(artifacts, Mapping):
        for key in wanted:
            value = artifacts.get(key)
            if value is None and not key.endswith(".jsonl"):
                value = artifacts.get(f"{key}.jsonl")
            if isinstance(value, Mapping):
                value = value.get("path")
            if value not in (None, ""):
                return value
    return None


def _resolve_manifest_path(root: Path, value: Any) -> Path | None:
    if isinstance(value, Mapping):
        value = value.get("path")
    if value in (None, "") or isinstance(value, (list, tuple)):
        return None
    path = Path(str(value)).expanduser()
    return (path if path.is_absolute() else root / path).resolve()


def _valid_manifest_structure(manifest: Mapping[str, Any], manifest_path: Path) -> bool:
    """Check local manifest references without loading large JSONL corpora.

    The generic runner remains the authority for complete package validation
    when its subprocess runs.  Discovery only needs to reject malformed or
    non-local candidates; eagerly parsing multi-hundred-megabyte corpora here
    would make a safe ``plan`` unexpectedly expensive.
    """

    root = manifest_path.parent
    evaluation = manifest.get("evaluation")
    evaluation_scope = evaluation.get("scope") if isinstance(evaluation, Mapping) else None
    scope = str(manifest.get("scope") or evaluation_scope or "global")
    if scope not in {"global", "document_local"}:
        return False

    documents = manifest.get("documents", manifest.get("documents_path"))
    if documents is None:
        documents = _manifest_artifact_value(manifest, ("corpus.jsonl", "corpus", "corpus_path"))
    if isinstance(documents, list):
        if not documents:
            return False
        for item in documents:
            if isinstance(item, str):
                item = {"path": item}
            if not isinstance(item, Mapping):
                return False
            references = (
                item.get("binary_path"),
                item.get("text_path"),
                item.get("path"),
                item.get("file"),
                item.get("file_path"),
                item.get("source"),
            )
            has_path = False
            for reference in references:
                if reference in (None, ""):
                    continue
                resolved = _resolve_manifest_path(root, reference)
                if resolved is not None and resolved.is_file():
                    has_path = True
                    break
            if item.get("content") is None and not has_path:
                return False
    else:
        document_path = _resolve_manifest_path(root, documents)
        if document_path is None or not (document_path.is_file() or document_path.is_dir()):
            return False

    questions = manifest.get("questions", manifest.get("questions_path"))
    if questions is None:
        questions = _manifest_artifact_value(manifest, ("questions.jsonl", "questions"))
    if isinstance(questions, list):
        if not questions or not all(
            isinstance(item, Mapping)
            and str(item.get("question", item.get("query", item.get("text", "")))).strip()
            for item in questions
        ):
            return False
    else:
        question_path = _resolve_manifest_path(root, questions)
        if question_path is None or not question_path.is_file():
            return False

    gold = manifest.get("gold", manifest.get("gold_path"))
    if gold is None:
        gold = _manifest_artifact_value(manifest, ("gold.jsonl", "gold"))
    if not isinstance(gold, list) and gold not in (None, ""):
        gold_path = _resolve_manifest_path(root, gold)
        if gold_path is None or not gold_path.is_file():
            return False
    return True


def _load_valid_package(manifest_path: Path) -> tuple[dict[str, Any], str] | None:
    raw = _load_json(manifest_path)
    if not isinstance(raw, Mapping):
        return None
    manifest = raw.get("package", raw)
    if not isinstance(manifest, Mapping):
        return None
    schema = manifest.get("schema") or manifest.get("package_schema") or manifest.get("schema_version")
    if schema != PACKAGE_SCHEMA:
        return None
    if _manifest_has_taas_provider(manifest):
        raise CampaignError(f"TAAS_PROVIDER_REFUSED:{manifest_path}")
    if not _valid_manifest_structure(manifest, manifest_path):
        return None
    protocol_tag = str(manifest.get("protocol_tag", manifest.get("protocol", "ADAPTED_PROTOCOL")))
    return dict(manifest), protocol_tag


def discover_manifests(package_root: Path | str, *, repo_root: Path | str = ROOT) -> list[PackageCandidate]:
    """Return only runner-loadable local packages in deterministic order."""

    root = _resolve(Path(repo_root).expanduser().resolve(), Path(package_root))
    if root.is_file():
        paths = [root]
    elif root.is_dir():
        paths = sorted(path for path in root.rglob("*") if path.is_file() and path.name in MANIFEST_NAMES)
    else:
        return []

    candidates: list[PackageCandidate] = []
    seen: set[tuple[str, str]] = set()
    for manifest_path in paths:
        if any(part.casefold() in {"omnidocbench", "lenovo"} for part in manifest_path.parts):
            continue
        loaded = _load_valid_package(manifest_path)
        if loaded is None:
            continue
        manifest, protocol_tag = loaded
        dataset = _manifest_dataset(manifest)
        if dataset not in EVALUATION_ORDER:
            continue
        if dataset in {_canonical_dataset(item) for item in EXCLUDED_DATASETS}:
            continue
        condition = _manifest_condition(manifest, manifest_path, root, dataset)
        key = (dataset, condition)
        if key in seen:
            continue
        seen.add(key)
        candidates.append(
            PackageCandidate(
                dataset=dataset,
                condition=condition,
                package_root=manifest_path.parent.resolve(),
                manifest_path=manifest_path.resolve(),
                protocol_tag=protocol_tag,
            )
        )

    def sort_key(candidate: PackageCandidate) -> tuple[int, int, str, str]:
        dataset_index = EVALUATION_ORDER.index(candidate.dataset)
        condition_names = CONDITION_ORDER.get(candidate.dataset, ())
        condition_index = condition_names.index(candidate.condition) if candidate.condition in condition_names else len(condition_names)
        return dataset_index, condition_index, candidate.condition, str(candidate.manifest_path)

    return sorted(candidates, key=sort_key)


# Friendly alias for callers that use the wording from the command help.
discover_packages = discover_manifests


def _runner_command(config: CampaignConfig, unit: CampaignUnit, stage: str, *, dry_run: bool) -> list[str]:
    command = [
        sys.executable,
        str(config.runner_path),
        stage,
        "--system",
        unit.system,
        "--package",
        str(unit.package),
        "--output-root",
        str(unit.runner_output_root),
        "--run-id",
        unit.run_id,
        "--repeats",
        str(config.repeats),
        "--top-k",
        str(config.top_k),
        "--poll-seconds",
        str(config.poll_seconds),
        "--service-timeout",
        str(config.service_timeout),
        "--provider-timeout",
        str(config.provider_timeout),
        "--upload-timeout",
        str(config.upload_timeout),
        "--index-timeout",
        str(config.index_timeout),
        "--query-timeout",
        str(config.query_timeout),
        "--qa-timeout",
        str(config.qa_timeout),
    ]
    if dry_run:
        command.append("--dry-run")
    return command


def _build_units(config: CampaignConfig, candidates: Sequence[PackageCandidate]) -> list[CampaignUnit]:
    units: list[CampaignUnit] = []
    ordinal = 0
    for candidate in candidates:
        for platform in PLATFORM_ORDER:
            ordinal += 1
            unit_id = _safe_slug(f"{ordinal:03d}-{candidate.dataset}-{candidate.condition}-{platform}", 120)
            run_id = _safe_slug(f"{config.campaign_id}-{unit_id}", 160)
            units.append(
                CampaignUnit(
                    ordinal=ordinal,
                    unit_id=unit_id,
                    dataset=candidate.dataset,
                    condition=candidate.condition,
                    platform=platform,
                    system=platform,
                    package=candidate.package_root,
                    manifest=candidate.manifest_path,
                    run_id=run_id,
                    runner_output_root=Path(config.output_root) / unit_id,
                )
            )
    return units


class CampaignStore:
    def __init__(self, config: CampaignConfig):
        self.config = config
        self.path = Path(config.checkpoint)
        self.progress_path = Path(config.progress_log)
        self.data: dict[str, Any] = self._load()

    def _load(self) -> dict[str, Any]:
        payload = _load_json(self.path)
        if payload is None:
            return {}
        if not isinstance(payload, dict) or payload.get("schema") != CHECKPOINT_SCHEMA:
            raise CampaignError(f"CHECKPOINT_INVALID:{self.path}")
        return payload

    def write(self) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        encoded = (json.dumps(self.data, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8")
        with tempfile.NamedTemporaryFile("wb", dir=self.path.parent, prefix=f".{self.path.name}.", delete=False) as handle:
            temp_path = Path(handle.name)
            handle.write(encoded)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp_path, self.path)

    def event(self, event: str, **fields: Any) -> None:
        payload = {"schema": PROGRESS_SCHEMA, "at": _utc_now(), "event": event, **fields}
        self.progress_path.parent.mkdir(parents=True, exist_ok=True)
        with self.progress_path.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(_safe_public(payload), ensure_ascii=False, sort_keys=True) + "\n")
            handle.flush()
            os.fsync(handle.fileno())

    def sync_plan(self, plan: dict[str, Any]) -> dict[str, Any]:
        old_units = self.data.get("units", [])
        if isinstance(old_units, dict):
            old_by_id = {str(key): dict(value) for key, value in old_units.items() if isinstance(value, Mapping)}
        else:
            old_by_id = {str(value.get("unit_id")): dict(value) for value in old_units if isinstance(value, Mapping) and value.get("unit_id")}

        units: list[dict[str, Any]] = []
        for unit in plan["units"]:
            current = dict(unit)
            previous = old_by_id.get(str(unit["unit_id"]), {})
            for key in (
                "status", "result", "preflight", "started_at", "completed_at",
                "attempts", "error", "run_id", "runner_artifact_root", "base_run_id",
            ):
                if key in previous:
                    current[key] = previous[key]
            current.setdefault("status", "pending")
            current.setdefault("attempts", 0)
            units.append(current)

        if not self.data:
            self.data = {
                "schema": CHECKPOINT_SCHEMA,
                "campaign_id": self.config.campaign_id,
                "created_at": _utc_now(),
                "repo_root": str(self.config.repo_root),
                "package_root": str(self.config.package_root),
                "output_root": str(self.config.output_root),
                "evaluation_order": list(EVALUATION_ORDER),
                "platform_order": list(PLATFORM_ORDER),
                "excluded_datasets": list(EXCLUDED_DATASETS),
                "policy": {
                    "download": False,
                    "provider": self.config.provider,
                    "max_competitor_services": 1,
                    "preserve_moi_containers": sorted(PROTECTED_MOI_CONTAINERS),
                },
                "active_service": None,
            }
        effective_config = plan.get("config")
        if not isinstance(effective_config, Mapping):
            effective_config = _checkpoint_config(self.config)
        self.data["config"] = dict(effective_config)
        # Keep the legacy top-level fields synchronized for operators and for
        # checkpoints produced before the nested config block was introduced.
        for key in ("repo_root", "package_root", "output_root", "campaign_id"):
            if key in effective_config:
                self.data[key] = effective_config[key]
        self.data["units"] = units
        self.data["missing_datasets"] = list(plan["missing_datasets"])
        self.data["updated_at"] = _utc_now()
        self.data["status"] = "planned"
        self.write()
        return self.data

    def unit(self, unit_id: str) -> dict[str, Any]:
        for unit in self.data.get("units", []):
            if unit.get("unit_id") == unit_id:
                return unit
        raise CampaignError(f"CHECKPOINT_UNIT_MISSING:{unit_id}")

    def update_unit(self, unit_id: str, **fields: Any) -> dict[str, Any]:
        unit = self.unit(unit_id)
        unit.update(fields)
        self.data["updated_at"] = _utc_now()
        self.write()
        return unit

    def set_active_service(self, platform: str | None) -> None:
        self.data["active_service"] = platform
        self.data["updated_at"] = _utc_now()
        self.write()


def _safe_public(value: Any, key: str | None = None) -> Any:
    if key and re.search(r"(?:api[_-]?key|token|password|secret|authorization)", key, re.IGNORECASE):
        return "<redacted>"
    if isinstance(value, Mapping):
        return {str(k): _safe_public(v, str(k)) for k, v in value.items()}
    if isinstance(value, list):
        return [_safe_public(item) for item in value]
    if isinstance(value, tuple):
        return [_safe_public(item) for item in value]
    return value


def _extract_result(stdout: Any) -> dict[str, Any]:
    text = str(stdout or "")
    decoder = json.JSONDecoder()
    for index in range(len(text) - 1, -1, -1):
        if text[index] != "{":
            continue
        try:
            value, _ = decoder.raw_decode(text[index:])
        except json.JSONDecodeError:
            continue
        if isinstance(value, dict):
            return dict(_safe_public(value))
    return {}


def _completed_status(status: Any) -> bool:
    return str(status or "").casefold().replace("-", "_") in {
        "success",
        "completed",
    }


class ServiceController:
    def __init__(self, orchestrator: "CampaignOrchestrator"):
        self.orchestrator = orchestrator
        self.config = orchestrator.config
        self.store = orchestrator.store
        active = self.store.data.get("active_service")
        self.active = _normal_platform(active) if active else None

    def _run(self, command: list[str], platform: str, action: str) -> dict[str, Any]:
        return self.orchestrator._run_external(command, platform=platform, action=action)

    def _running(self) -> dict[str, list[str]]:
        command = ["docker", "ps", "--format", "{{.Names}}"]
        result = self.orchestrator._run_external(command, platform="host", action="inspect-running", allow_failure=True)
        if result["returncode"] != 0:
            raise CampaignError("DOCKER_INSPECTION_FAILED")
        names = [line.strip() for line in str(result.get("stdout", "")).splitlines() if line.strip()]
        found: dict[str, list[str]] = {platform: [] for platform in PLATFORM_ORDER}
        for name in names:
            for platform, spec in SERVICE_SPECS.items():
                if spec.matches_container(name):
                    found[platform].append(name)
        return {platform: names for platform, names in found.items() if names}

    def _stop(self, platform: str) -> None:
        spec = SERVICE_SPECS[platform]
        self._run(spec.stop_command(self.config.repo_root), platform, "stop")
        self.active = None
        self.store.set_active_service(None)
        self.store.event("service_stopped", platform=platform)

    def _start(self, platform: str) -> None:
        spec = SERVICE_SPECS[platform]
        self._run(spec.start_command(self.config.repo_root), platform, "start")
        self.active = platform
        self.store.set_active_service(platform)
        self.store.event("service_started", platform=platform)

    def ensure(self, platform: str) -> None:
        platform = _normal_platform(platform)
        spec = SERVICE_SPECS[platform]
        if self.active == platform:
            # Re-check the host even when the desired service is unchanged.
            # This catches an independently started second competitor without
            # treating protected MOI containers as campaign services.
            running = self._running()
            if len(running) > 1:
                raise CampaignError("COMPETITOR_CONCURRENCY_REFUSED: multiple named competitor services are running")
            if not spec.is_reusable(running.get(platform, ())):
                self._start(platform)
            return
        if self.active is not None:
            self._stop(self.active)

        running = self._running()
        other_platforms = [name for name in running if name != platform]
        if len(running) > 1:
            raise CampaignError("COMPETITOR_CONCURRENCY_REFUSED: multiple named competitor services are running")
        if other_platforms:
            # Only the named project/container for the observed competitor is
            # stopped.  MOI parser and MatrixOne names are never in this map.
            self._stop(other_platforms[0])
        if platform in running and spec.is_reusable(running[platform]):
            self.active = platform
            self.store.set_active_service(platform)
            self.store.event("service_reused", platform=platform)
        else:
            self._start(platform)

    def stop_active(self) -> None:
        if self.active is not None:
            self._stop(self.active)


class CampaignOrchestrator:
    def __init__(self, config: CampaignConfig):
        self.config = config
        self.store = CampaignStore(config)

    def _plan(self) -> dict[str, Any]:
        candidates = discover_manifests(self.config.package_root, repo_root=self.config.repo_root)
        units = _build_units(self.config, candidates)
        available = {candidate.dataset for candidate in candidates}
        missing = [dataset for dataset in EVALUATION_ORDER if dataset not in available]
        public_units = [
            unit.public(
                _runner_command(
                    self.config,
                    unit,
                    self.config.evaluation_stage,
                    dry_run=not self.config.execute,
                )
            )
            for unit in units
        ]
        return {
            "schema": CHECKPOINT_SCHEMA,
            "campaign_id": self.config.campaign_id,
            "config": _checkpoint_config(self.config),
            "evaluation_order": list(EVALUATION_ORDER),
            "platform_order": list(PLATFORM_ORDER),
            "excluded_datasets": list(EXCLUDED_DATASETS),
            "missing_datasets": missing,
            "policy": {
                "download": False,
                "default_mode": "execute" if self.config.execute else "preview_dry_run",
                "provider": self.config.provider,
                "evaluation_stage": self.config.evaluation_stage,
                "max_competitor_services": 1,
                "preserve_moi_containers": sorted(PROTECTED_MOI_CONTAINERS),
            },
            "packages": [candidate.public() for candidate in candidates],
            "units": public_units,
        }

    def _ensure_plan(self) -> dict[str, Any]:
        plan = self._plan()
        self.store.sync_plan(plan)
        return plan

    def _run_external(
        self,
        command: list[str],
        *,
        platform: str,
        action: str,
        allow_failure: bool = False,
    ) -> dict[str, Any]:
        if not self.config.execute:
            return {
                "status": "PREVIEW",
                "returncode": 0,
                "command": list(command),
                "platform": platform,
                "action": action,
            }
        env = load_campaign_env(self.config.repo_root, platform if platform in PLATFORM_ORDER else "dify_local")
        try:
            completed = subprocess.run(
                command,
                cwd=self.config.repo_root,
                env=env,
                text=True,
                capture_output=True,
                check=False,
            )
        except OSError as exc:
            if allow_failure:
                return {
                    "status": "ERROR",
                    "returncode": 127,
                    "command": list(command),
                    "platform": platform,
                    "action": action,
                    "error": type(exc).__name__,
                    "stdout": "",
                }
            raise CampaignError(f"COMMAND_EXECUTION_FAILED:{action}:{type(exc).__name__}") from exc
        result = {
            "status": "SUCCESS" if completed.returncode == 0 else "ERROR",
            "returncode": int(completed.returncode),
            "command": list(command),
            "platform": platform,
            "action": action,
            "stdout": str(getattr(completed, "stdout", "") or ""),
        }
        if completed.returncode != 0 and not allow_failure:
            raise CampaignError(f"COMMAND_FAILED:{action}:exit-{completed.returncode}")
        return result

    def _invoke_runner(self, unit: Mapping[str, Any], stage: str, *, dry_run: bool) -> dict[str, Any]:
        runner_unit = CampaignUnit(
            ordinal=int(unit["ordinal"]),
            unit_id=str(unit["unit_id"]),
            dataset=str(unit["dataset"]),
            condition=str(unit["condition"]),
            platform=str(unit["platform"]),
            system=str(unit["system"]),
            package=Path(str(unit["package"])),
            manifest=Path(str(unit["manifest"])),
            run_id=str(unit["run_id"]),
            runner_output_root=Path(str(unit["runner_output_root"])),
        )
        command = _runner_command(self.config, runner_unit, stage, dry_run=dry_run)
        result = self._run_external(command, platform=runner_unit.platform, action=f"runner-{stage}")
        parsed = _extract_result(result.get("stdout", ""))
        if not parsed.get("status") and not dry_run:
            summary = _load_json(runner_unit.runner_output_root / runner_unit.run_id / "summary.json")
            if isinstance(summary, Mapping):
                parsed = dict(_safe_public(summary))
        return {
            "status": parsed.get("status", result.get("status")),
            "returncode": result.get("returncode", 0),
            "run_id": parsed.get("run_id", runner_unit.run_id),
            "command": command,
            "result_keys": sorted(parsed.keys()),
        }

    def plan(self) -> dict[str, Any]:
        plan = self._ensure_plan()
        self.store.event("plan_created", unit_count=len(plan["units"]), missing_datasets=plan["missing_datasets"])
        return {**plan, "checkpoint": str(self.config.checkpoint), "progress_log": str(self.config.progress_log)}

    def preflight(self) -> dict[str, Any]:
        plan = self._ensure_plan()
        services: list[dict[str, Any]] = []
        used_platforms = [platform for platform in PLATFORM_ORDER if any(unit["platform"] == platform for unit in plan["units"])]
        for platform in used_platforms:
            spec = SERVICE_SPECS[platform]
            command = (
                spec.compose_config_command(self.config.repo_root)
                if spec.compose_path is not None
                else ["bash", str(_resolve(self.config.repo_root, spec.launcher or MAXKB_LAUNCHER)), "verify-image"]
            )
            if self.config.execute:
                outcome = self._run_external(command, platform=platform, action="service-preflight", allow_failure=True)
                services.append({
                    "platform": platform,
                    "command": command,
                    "status": outcome["status"],
                    "returncode": outcome["returncode"],
                    "material_exists": self._service_material_exists(spec),
                })
            else:
                services.append({
                    "platform": platform,
                    "command": command,
                    "status": "PREVIEW",
                    "returncode": 0,
                    "material_exists": self._service_material_exists(spec),
                })

        runner_results: list[dict[str, Any]] = []
        for unit in plan["units"]:
            result = self._invoke_runner(unit, "preflight", dry_run=not self.config.execute)
            runner_results.append({"unit_id": unit["unit_id"], **result})
            self.store.update_unit(unit["unit_id"], preflight={k: v for k, v in result.items() if k != "command"})

        status = "PREVIEW" if not self.config.execute else (
            "SUCCESS" if all(item["status"] == "SUCCESS" for item in services + runner_results) else "BLOCKED"
        )
        self.store.data["status"] = status.casefold()
        self.store.write()
        self.store.event("preflight_complete", status=status, unit_count=len(runner_results))
        return {
            "schema": CHECKPOINT_SCHEMA,
            "status": status,
            "checkpoint": str(self.config.checkpoint),
            "services": services,
            "units": runner_results,
            "missing_datasets": plan["missing_datasets"],
        }

    def _service_material_exists(self, spec: ServiceSpec) -> bool:
        path = spec.compose_path or spec.launcher
        return bool(path and _resolve(self.config.repo_root, path).is_file())

    def _preview_run_commands(self, units: Sequence[Mapping[str, Any]]) -> list[dict[str, Any]]:
        commands: list[dict[str, Any]] = []
        previous: str | None = None
        for unit in units:
            if _completed_status(unit.get("status")):
                continue
            platform = str(unit["platform"])
            if previous != platform:
                if previous is not None:
                    commands.append({"action": "stop", "platform": previous, "command": SERVICE_SPECS[previous].stop_command(self.config.repo_root)})
                commands.append({"action": "start", "platform": platform, "command": SERVICE_SPECS[platform].start_command(self.config.repo_root)})
                previous = platform
            commands.append({
                "action": "runner-all",
                "platform": platform,
                "unit_id": unit["unit_id"],
                "command": _runner_command(self.config, CampaignUnit(
                    ordinal=int(unit["ordinal"]), unit_id=str(unit["unit_id"]), dataset=str(unit["dataset"]),
                    condition=str(unit["condition"]), platform=platform, system=str(unit["system"]),
                    package=Path(str(unit["package"])), manifest=Path(str(unit["manifest"])),
                    run_id=str(unit["run_id"]), runner_output_root=Path(str(unit["runner_output_root"])),
                ), "all", dry_run=True),
            })
        if previous is not None:
            commands.append({"action": "stop", "platform": previous, "command": SERVICE_SPECS[previous].stop_command(self.config.repo_root)})
        return commands

    def run(self) -> dict[str, Any]:
        plan = self._ensure_plan()
        units = self.store.data.get("units", [])
        if not self.config.execute:
            preview = self._preview_run_commands(units)
            self.store.data["status"] = "dry_run"
            self.store.write()
            self.store.event("run_previewed", command_count=len(preview))
            return {
                "schema": CHECKPOINT_SCHEMA,
                "status": "DRY_RUN",
                "commands": preview,
                "units": units,
                "missing_datasets": plan["missing_datasets"],
                "checkpoint": str(self.config.checkpoint),
                "progress_log": str(self.config.progress_log),
            }

        controller = ServiceController(self)
        campaign_status = "SUCCESS"
        try:
            for unit in units:
                if _completed_status(unit.get("status")):
                    self.store.event("unit_resumed_completed", unit_id=unit["unit_id"], status=unit["status"])
                    continue
                unit_id = str(unit["unit_id"])
                previous_status = str(unit.get("status", "pending")).casefold()
                interrupted_resume = previous_status == "running" and int(unit.get("attempts", 0) or 0) > 0
                attempts = int(unit.get("attempts", 0) or 0) if interrupted_resume else int(unit.get("attempts", 0) or 0) + 1
                if attempts > 1 and not interrupted_resume:
                    base_run_id = str(unit.get("base_run_id") or unit["run_id"])
                    retry_run_id = f"{base_run_id}-attempt-{attempts}"
                    retry_artifact_root = str(Path(str(unit["runner_output_root"])) / retry_run_id)
                    self.store.update_unit(
                        unit_id,
                        base_run_id=base_run_id,
                        run_id=retry_run_id,
                        runner_artifact_root=retry_artifact_root,
                    )
                self.store.update_unit(unit_id, status="running", attempts=attempts, started_at=_utc_now(), error=None)
                self.store.event(
                    "unit_resumed_interrupted" if interrupted_resume else "unit_started",
                    unit_id=unit_id,
                    platform=unit["platform"],
                    dataset=unit["dataset"],
                    condition=unit["condition"],
                    run_id=unit["run_id"],
                )
                try:
                    controller.ensure(str(unit["platform"]))
                    runner_result = self._invoke_runner(
                        unit,
                        self.config.evaluation_stage,
                        dry_run=False,
                    )
                    unit_status = "completed" if int(runner_result["returncode"]) == 0 and _completed_status(runner_result["status"]) else "blocked"
                    self.store.update_unit(unit_id, status=unit_status, result={"status": runner_result["status"], "returncode": runner_result["returncode"], "run_id": runner_result["run_id"]}, completed_at=_utc_now())
                    self.store.event("unit_completed" if unit_status == "completed" else "unit_blocked", unit_id=unit_id, status=runner_result["status"])
                    if unit_status != "completed":
                        campaign_status = "BLOCKED"
                        break
                except CampaignError as exc:
                    self.store.update_unit(unit_id, status="blocked", error=str(exc), completed_at=_utc_now())
                    self.store.event("unit_blocked", unit_id=unit_id, reason=type(exc).__name__)
                    campaign_status = "BLOCKED"
                    break
        finally:
            try:
                controller.stop_active()
            except CampaignError as exc:
                campaign_status = "BLOCKED"
                self.store.event("service_stop_failed", reason=type(exc).__name__)

        self.store.data["status"] = campaign_status.casefold()
        self.store.write()
        self.store.event("run_complete", status=campaign_status)
        return {
            "schema": CHECKPOINT_SCHEMA,
            "status": campaign_status,
            "units": self.store.data.get("units", []),
            "missing_datasets": plan["missing_datasets"],
            "checkpoint": str(self.config.checkpoint),
            "progress_log": str(self.config.progress_log),
        }

    def status(self) -> dict[str, Any]:
        if not self.store.data:
            return {
                "schema": CHECKPOINT_SCHEMA,
                "status": "NOT_FOUND",
                "checkpoint": str(self.config.checkpoint),
                "progress_log": str(self.config.progress_log),
            }
        return {
            "schema": CHECKPOINT_SCHEMA,
            "status": str(self.store.data.get("status", "unknown")).upper(),
            "campaign_id": self.store.data.get("campaign_id"),
            "active_service": self.store.data.get("active_service"),
            "missing_datasets": self.store.data.get("missing_datasets", []),
            "units": self.store.data.get("units", []),
            "checkpoint": str(self.config.checkpoint),
            "progress_log": str(self.config.progress_log),
        }


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)
    for name in ("plan", "preflight", "run", "status"):
        subparser = subparsers.add_parser(name, help=f"{name} the local competitor campaign")
        # Suppressed defaults let ``run --checkpoint`` distinguish an option
        # that was actually supplied from an argparse default.  The latter
        # must come from the checkpoint's effective experiment config.
        subparser.add_argument("--repo-root", type=Path, default=argparse.SUPPRESS)
        subparser.add_argument("--package-root", type=Path, default=argparse.SUPPRESS)
        subparser.add_argument("--output-root", type=Path, default=argparse.SUPPRESS)
        subparser.add_argument("--checkpoint", "--campaign-file", dest="checkpoint", type=Path, default=argparse.SUPPRESS)
        subparser.add_argument("--progress-log", type=Path, default=argparse.SUPPRESS)
        subparser.add_argument("--campaign-id", default=argparse.SUPPRESS)
        subparser.add_argument("--runner-path", type=Path, default=argparse.SUPPRESS)
        subparser.add_argument("--execute", action="store_true", help="execute named local commands; default is preview/dry-run")
        subparser.add_argument("--download", action="store_true", help=argparse.SUPPRESS)
        subparser.add_argument("--provider", default=argparse.SUPPRESS)
        subparser.add_argument(
            "--evaluation-stage",
            choices=("all", "qa"),
            default=argparse.SUPPRESS,
            help="runner stage; qa skips the standalone direct-retrieval evaluation",
        )
        subparser.add_argument("--repeats", type=int, default=argparse.SUPPRESS)
        subparser.add_argument("--top-k", type=int, default=argparse.SUPPRESS)
        subparser.add_argument("--poll-seconds", type=float, default=argparse.SUPPRESS)
        subparser.add_argument("--service-timeout", type=float, default=argparse.SUPPRESS)
        subparser.add_argument("--provider-timeout", type=float, default=argparse.SUPPRESS)
        subparser.add_argument("--upload-timeout", type=float, default=argparse.SUPPRESS)
        subparser.add_argument("--index-timeout", type=float, default=argparse.SUPPRESS)
        subparser.add_argument("--query-timeout", type=float, default=argparse.SUPPRESS)
        subparser.add_argument("--qa-timeout", type=float, default=argparse.SUPPRESS)
    return parser


def _config_from_args(args: argparse.Namespace) -> CampaignConfig:
    command = str(getattr(args, "command", ""))
    repo_arg = getattr(args, "repo_root", _MISSING)
    repo_for_lookup = Path(ROOT if repo_arg is _MISSING else repo_arg).expanduser().resolve()
    checkpoint_arg = getattr(args, "checkpoint", _MISSING)
    checkpoint_for_lookup = _resolve(
        repo_for_lookup,
        DEFAULT_CHECKPOINT if checkpoint_arg is _MISSING else checkpoint_arg,
    )
    stored = _checkpoint_restore_values(checkpoint_for_lookup) if command == "run" else {}

    def value(name: str, default: Any) -> Any:
        explicit = getattr(args, name, _MISSING)
        if explicit is not _MISSING:
            return explicit
        return stored.get(name, default)

    # ``execute`` and ``download`` are command controls.  In particular,
    # execute is intentionally not restored: resuming a checkpoint must still
    # require the operator to opt into starting services and making requests.
    return CampaignConfig(
        repo_root=value("repo_root", ROOT),
        package_root=value("package_root", None),
        output_root=value("output_root", None),
        checkpoint=checkpoint_for_lookup,
        progress_log=value("progress_log", None),
        campaign_id=value("campaign_id", DEFAULT_CAMPAIGN_ID),
        execute=bool(getattr(args, "execute", False)),
        runner_path=value("runner_path", None),
        repeats=int(value("repeats", DEFAULT_REPEATS)),
        top_k=int(value("top_k", DEFAULT_TOP_K)),
        poll_seconds=float(value("poll_seconds", DEFAULT_POLL_SECONDS)),
        service_timeout=float(value("service_timeout", DEFAULT_SERVICE_TIMEOUT)),
        provider_timeout=float(value("provider_timeout", DEFAULT_PROVIDER_TIMEOUT)),
        upload_timeout=float(value("upload_timeout", DEFAULT_UPLOAD_TIMEOUT)),
        index_timeout=float(value("index_timeout", DEFAULT_INDEX_TIMEOUT)),
        query_timeout=float(value("query_timeout", DEFAULT_QUERY_TIMEOUT)),
        qa_timeout=float(value("qa_timeout", DEFAULT_QA_TIMEOUT)),
        provider=value("provider", DEFAULT_PROVIDER),
        evaluation_stage=value("evaluation_stage", "all"),
        download=bool(getattr(args, "download", False)),
    )


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(list(argv) if argv is not None else None)
    try:
        orchestrator = CampaignOrchestrator(_config_from_args(args))
        result = getattr(orchestrator, args.command)()
        print(json.dumps(_safe_public(result), ensure_ascii=False, indent=2, sort_keys=True))
        return 0 if result.get("status") not in {"BLOCKED", "ERROR"} else 1
    except CampaignError as exc:
        print(json.dumps({"status": "ERROR", "error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
