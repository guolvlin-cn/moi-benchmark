def _resolve(root: Path, value: Path | str) -> Path:
    path = Path(value).expanduser()
    return path if path.is_absolute() else root / path


def _safe_slug(value: Any, limit: int = 80) -> str:
    text = re.sub(r"[^A-Za-z0-9._-]+", "-", str(value)).strip(".-") or "item"
    return text[:limit]


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def _canonical_dataset(value: Any) -> str:
    raw = str(value or "").strip().casefold()
    normalized = re.sub(r"[^a-z0-9]+", "-", raw).strip("-")
    if normalized in DATASET_ALIASES:
        return DATASET_ALIASES[normalized]
    compact = normalized.replace("-", "")
    if compact in {"mmdocir", "mmdocrag", "docbench", "wikieval"}:
        return compact
    return normalized


def _reject_taas(value: Any, *, field: str = "value") -> None:
    text = str(value or "").casefold()
    if any(marker in text for marker in SECRET_MARKERS):
        raise CampaignError(f"TAAS_PROVIDER_REFUSED:{field}")


