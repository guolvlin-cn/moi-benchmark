@dataclass(frozen=True)
class ServiceSpec:
    platform: str
    system: str
    compose_path: Path | None = None
    project: str | None = None
    launcher: Path | None = None
    container_patterns: tuple[str, ...] = ()
    scale: tuple[str, int] | None = None
    required_container_groups: tuple[tuple[str, ...], ...] = ()

    def compose_config_command(self, repo_root: Path) -> list[str]:
        if self.compose_path is None or self.project is None:
            raise CampaignError(f"SERVICE_CONFIG_UNAVAILABLE:{self.platform}")
        command = [
            "docker",
            "compose",
            "-p",
            self.project,
            "-f",
            str(_resolve(repo_root, self.compose_path)),
            "config",
            "--quiet",
        ]
        return command

    def start_command(self, repo_root: Path) -> list[str]:
        if self.launcher is not None:
            return ["bash", str(_resolve(repo_root, self.launcher)), "start"]
        if self.compose_path is None or self.project is None:
            raise CampaignError(f"SERVICE_START_UNAVAILABLE:{self.platform}")
        command = [
            "docker",
            "compose",
            "-p",
            self.project,
            "-f",
            str(_resolve(repo_root, self.compose_path)),
            "up",
            "-d",
            "--pull",
            "never",
        ]
        if self.scale is not None:
            service, replicas = self.scale
            command.extend(["--scale", f"{service}={replicas}"])
        return command

    def stop_command(self, repo_root: Path) -> list[str]:
        if self.launcher is not None:
            return ["bash", str(_resolve(repo_root, self.launcher)), "stop"]
        if self.compose_path is None or self.project is None:
            raise CampaignError(f"SERVICE_STOP_UNAVAILABLE:{self.platform}")
        # Deliberately no -v, --remove-orphans, or unscoped `docker down`.
        return [
            "docker",
            "compose",
            "-p",
            self.project,
            "-f",
            str(_resolve(repo_root, self.compose_path)),
            "down",
        ]

    def matches_container(self, name: str) -> bool:
        return any(self._matches_pattern(name, pattern) for pattern in self.container_patterns)

    @staticmethod
    def _matches_pattern(name: str, pattern: str) -> bool:
        return name == pattern or name.startswith(pattern)

    def is_reusable(self, names: Iterable[str]) -> bool:
        matching_names = tuple(name for name in names if self.matches_container(name))
        if not matching_names:
            return False
        return all(
            any(
                self._matches_pattern(name, pattern)
                for name in matching_names
                for pattern in group
            )
            for group in self.required_container_groups
        )


